import { readFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import type { Bindings, Contract, GeneratedModels, Schema } from "./types.ts";

export const root = fileURLToPath(new URL("../../../", import.meta.url));
const templates = path.join(root, "tools/codegen/templates");
export const banner = "Generated by @ateve/codegen. DO NOT EDIT.";
// JSON files are validated at their consuming boundary.
export const readJson = <T = unknown>(file: string): T =>
  JSON.parse(readFileSync(file, "utf8")) as T;
const camel = (name: string): string =>
  name.replace(/_([a-z])/g, (_: string, c: string) => c.toUpperCase());
const typeOf = (schema: Schema): string =>
  (Array.isArray(schema.type) ? schema.type.find((type) => type !== "null") : schema.type) ?? "";

function template(file: string, context: Record<string, unknown>): string {
  const absolute = path.join(templates, file);
  if (!existsSync(absolute)) return "";
  return readFileSync(absolute, "utf8")
    .replace(/\{\{([\w.]+)\}\}/g, (_: string, key: string) => {
      const value = key
        .split(".")
        .reduce<unknown>(
          (current, part) =>
            current && typeof current === "object"
              ? (current as Record<string, unknown>)[part]
              : undefined,
          context,
        );
      if (value === undefined) throw new Error(`Missing template value ${key} in ${file}`);
      return String(value);
    })
    .trimEnd();
}

// Fail closed: this is a model generator for the documented subset, not a
// general OpenAPI client generator. New structural keywords require support.
const keywords = new Set([
  "type",
  "$ref",
  "properties",
  "required",
  "items",
  "additionalProperties",
  "enum",
  "format",
  "description",
  "minimum",
  "maximum",
  "minLength",
  "maxLength",
  "maxItems",
  "pattern",
  "x-sdk-kind",
]);

export function validate(api: Contract, bindings: Bindings): void {
  if (api.openapi !== "3.1.0") throw new Error("Expected OpenAPI 3.1.0");
  if (!api.info?.version || !api.paths?.["/v1/search"]?.post)
    throw new Error("Missing API metadata or search operation");
  const schemas = api.components?.schemas;
  if (!schemas || !Object.keys(schemas).length) throw new Error("Missing schemas");
  function inspect(schema: Schema | undefined, location: string): void {
    if (!schema || typeof schema !== "object" || Array.isArray(schema))
      throw new Error(`Invalid schema at ${location}`);
    for (const key of Object.keys(schema)) {
      if (!keywords.has(key)) throw new Error(`Unsupported keyword ${key} at ${location}`);
    }
    if (schema.$ref) {
      const name = schema.$ref.replace("#/components/schemas/", "");
      if (schema.$ref !== `#/components/schemas/${name}` || !schemas[name])
        throw new Error(`Unresolved reference ${schema.$ref}`);
      if (Object.keys(schema).some((key) => !["$ref", "description"].includes(key)))
        throw new Error(`Unsupported reference siblings at ${location}`);
      return;
    }
    const type = typeOf(schema);
    if (!["string", "integer", "number", "boolean", "object", "array"].includes(type))
      throw new Error(`Unsupported type at ${location}`);
    if (Array.isArray(schema.type) && (schema.type.length !== 2 || !schema.type.includes("null")))
      throw new Error(`Unsupported union at ${location}`);
    if (schema.format && !["date-time", "int64"].includes(schema.format))
      throw new Error(`Unsupported format ${schema.format}`);
    if (
      (schema.format === "date-time" && type !== "string") ||
      (schema.format === "int64" && type !== "integer")
    )
      throw new Error(`Invalid format at ${location}`);
    if (schema.enum && (type !== "string" || schema.enum.some((item) => typeof item !== "string")))
      throw new Error(`Unsupported enum at ${location}`);
    if (location.includes(".") && (schema.enum || schema.properties))
      throw new Error(`Unsupported inline model at ${location}; use a named schema and $ref`);
    if (type === "array") inspect(schema.items, `${location}.items`);
    if (
      schema.additionalProperties !== undefined &&
      typeof schema.additionalProperties !== "boolean"
    )
      throw new Error(`Unsupported map value schema at ${location}`);
    for (const [name, property] of Object.entries(schema.properties ?? {}))
      inspect(property, `${location}.${name}`);
    if (schema.required?.some((name) => !schema.properties?.[name]))
      throw new Error(`Unknown required field at ${location}`);
    if (schema["x-sdk-kind"] && !["request", "response"].includes(schema["x-sdk-kind"]))
      throw new Error(`Invalid SDK kind at ${location}`);
  }
  for (const [name, schema] of Object.entries(schemas)) {
    if (!/^[A-Z][A-Za-z0-9]*$/.test(name)) throw new Error(`Invalid model name ${name}`);
    inspect(schema, name);
    for (const field of Object.keys(schema.properties ?? {}))
      if (!/^[a-z][a-z0-9_]*$/.test(field)) throw new Error(`Invalid field ${name}.${field}`);
  }
  for (const [name, options] of Object.entries(bindings.models ?? {})) {
    if (!schemas[name]) throw new Error(`Unknown model binding ${name}`);
    if (Object.keys(options).some((key) => !["generate", "javaImports"].includes(key)))
      throw new Error(`Unsupported model binding ${name}`);
    if (options.generate !== undefined && typeof options.generate !== "boolean")
      throw new Error(`Invalid generate binding ${name}`);
    if (
      options.javaImports &&
      (!Array.isArray(options.javaImports) ||
        options.javaImports.some((value) => typeof value !== "string"))
    )
      throw new Error(`Invalid Java imports for ${name}`);
  }
  for (const [key, options] of Object.entries(bindings.fields ?? {})) {
    const [model, field] = key.split(".");
    if (!schemas[model]?.properties?.[field]) throw new Error(`Unknown field binding ${key}`);
    if (Object.keys(options).some((language) => language !== "python"))
      throw new Error(`Unsupported language binding ${key}`);
    const python = options.python ?? {};
    if (
      Object.keys(python).some(
        (option) => !["required", "strict", "defaultFactory"].includes(option),
      )
    )
      throw new Error(`Unsupported Python binding ${key}`);
    for (const option of ["required", "strict"])
      if (python[option] !== undefined && typeof python[option] !== "boolean")
        throw new Error(`Invalid ${option} binding ${key}`);
    if (
      python.defaultFactory !== undefined &&
      (python.defaultFactory !== "list" || typeOf(schemas[model].properties![field]) !== "array")
    )
      throw new Error(`Unsupported default factory ${key}`);
  }
  // Resolve references in operation bodies too, not just model properties.
  const visit = (value: unknown): void => {
    if (!value || typeof value !== "object") return;
    const ref = (value as Record<string, unknown>).$ref;
    if (typeof ref === "string" && !schemas[ref.replace("#/components/schemas/", "")])
      throw new Error(`Unresolved operation reference ${ref}`);
    for (const child of Object.values(value)) visit(child);
  };
  visit(api.paths);
}

function tsType(schema: Schema): string {
  let result;
  if (schema.$ref) result = schema.$ref.split("/").at(-1)!;
  else if (schema.enum) result = schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  else if (typeOf(schema) === "array")
    result = `(${tsType(schema.items!)})[]`.replace(/\((\w+)\)/, "$1");
  else
    result = (
      {
        string: "string",
        integer: "number",
        number: "number",
        boolean: "boolean",
        object: "Record<string, unknown>",
      } as Record<string, string>
    )[typeOf(schema)];
  return result + (Array.isArray(schema.type) ? " | null" : "");
}

function pyType(schema: Schema): string {
  if (schema.$ref) return schema.$ref.split("/").at(-1)!;
  if (typeOf(schema) === "array") return `List[${pyType(schema.items!)}]`;
  if (schema.format === "date-time") return "datetime";
  return (
    {
      string: "str",
      integer: "int",
      number: "float",
      boolean: "bool",
      object: "Dict[str, Any]",
    } as Record<string, string>
  )[typeOf(schema)];
}

function javaType(schema: Schema): string {
  if (schema.$ref) return schema.$ref.split("/").at(-1)!;
  if (typeOf(schema) === "array") return `List<${javaType(schema.items!)}>`;
  if (schema.format === "date-time") return "Instant";
  if (schema.format === "int64") return "Long";
  return (
    {
      string: "String",
      integer: "Integer",
      number: "Double",
      boolean: "Boolean",
      object: "Map<String, Object>",
    } as Record<string, string>
  )[typeOf(schema)];
}

export function render(api: Contract, bindings: Bindings): GeneratedModels {
  validate(api, bindings);
  const output: GeneratedModels = { js: {}, python: {}, java: {} };
  const tsModels: string[] = [];
  const pyModels = [template("python/preamble.tpl", {})];
  for (const [name, schema] of Object.entries(api.components.schemas)) {
    if (bindings.models?.[name]?.generate === false) continue;
    if (schema.enum) {
      tsModels.push(`export type ${name} = ${tsType(schema)};`);
      pyModels.push(
        `class ${name}(str, Enum):\n${schema.enum.map((value) => `    ${value.toUpperCase()} = ${JSON.stringify(value)}`).join("\n")}`,
      );
      output.java[`src/main/java/ai/ateve/models/${name}.java`] =
        "// " +
        banner +
        "\n" +
        template("java/enum.tpl", {
          name,
          description: schema.description ?? name,
          values: schema.enum
            .map((value) => `    ${value.toUpperCase()}(${JSON.stringify(value)})`)
            .join(",\n"),
        }) +
        "\n";
      continue;
    }
    if (typeOf(schema) !== "object" || !schema.properties)
      throw new Error(`Top-level model ${name} must be an enum or object with properties`);
    const entries = Object.entries(schema.properties);
    tsModels.push(
      template("ts/model.tpl", {
        name,
        fields: entries
          .map(([field, prop]) => {
            const comment = prop.description
              ? `  /** ${prop.description.replaceAll("*/", "* /")} */\n`
              : "";
            return (
              comment +
              `  ${camel(field)}${schema.required?.includes(field) ? "" : "?"}: ${tsType(prop)};`
            );
          })
          .join("\n"),
      }),
    );
    pyModels.push(
      template("python/model.tpl", {
        name,
        base: schema["x-sdk-kind"] === "request" ? "RequestModel" : "ResponseModel",
        fields:
          entries
            .map(([field, prop]) => {
              const options = bindings.fields?.[`${name}.${field}`]?.python ?? {};
              const required = options.required ?? schema.required?.includes(field) ?? false;
              const factory = options.defaultFactory;
              const nullable = !required || Array.isArray(prop.type);
              const type = nullable && !factory ? `Optional[${pyType(prop)}]` : pyType(prop);
              const args: string[] = [];
              if (factory) args.push(`default_factory=${factory}`);
              else if (!required) args.push("default=None");
              if (schema["x-sdk-kind"] === "request") {
                for (const [keyword, argument] of Object.entries({
                  minimum: "ge",
                  maximum: "le",
                  minLength: "min_length",
                  maxLength: "max_length",
                  maxItems: "max_length",
                  pattern: "pattern",
                })) {
                  if (prop[keyword] !== undefined)
                    args.push(`${argument}=${JSON.stringify(prop[keyword])}`);
                }
              }
              if (options.strict) args.push("strict=True");
              const value =
                args.length && (factory || args.some((arg) => arg !== "default=None"))
                  ? ` = Field(${args.join(", ")})`
                  : !required
                    ? " = None"
                    : "";
              return `    ${field}: ${type}${value}`;
            })
            .join("\n") || "    pass",
        hook: template(`python/${name}.tpl`, {}),
      }),
    );

    const imports = new Set(bindings.models?.[name]?.javaImports ?? []);
    const isRequest = schema["x-sdk-kind"] === "request";
    const fields: string[] = [];
    const assignments: string[] = [];
    const accessors: string[] = [];
    const builderFields: string[] = [];
    const setters: string[] = [];
    const context: Record<string, unknown> = {};
    for (const [field, prop] of entries) {
      const sdkField = camel(field);
      const type = javaType(prop);
      if (type.includes("List<")) imports.add("java.util.List");
      if (type.includes("Map<")) imports.add("java.util.Map");
      if (!isRequest && (type.startsWith("List<") || type.startsWith("Map<")))
        imports.add("java.util.Collections");
      let annotation = "";
      if (type === "Instant") {
        imports.add("java.time.Instant");
        imports.add("ai.ateve.internal.InstantMillis");
        imports.add("com.fasterxml.jackson.databind.annotation.JsonDeserialize");
        imports.add("com.fasterxml.jackson.databind.annotation.JsonSerialize");
        annotation =
          "    @JsonSerialize(using = InstantMillis.Serializer.class)\n    @JsonDeserialize(using = InstantMillis.Deserializer.class)\n";
      }
      fields.push(`${annotation}    private ${isRequest ? "final " : ""}${type} ${sdkField};`);
      const collection = type.startsWith("List<")
        ? "List"
        : type.startsWith("Map<")
          ? "Map"
          : undefined;
      assignments.push(
        `        this.${sdkField} = ${collection ? `b.${sdkField} == null ? null : ${collection}.copyOf(b.${sdkField})` : `b.${sdkField}`};`,
      );
      const getter =
        !isRequest && collection
          ? `${sdkField} == null ? null : Collections.unmodifiable${collection}(${sdkField})`
          : sdkField;
      accessors.push(`    public ${type} ${sdkField}() { return ${getter}; }`);
      builderFields.push(`        private ${type} ${sdkField};`);
      // Preserve existing parameter names on domain-list builder methods.
      const parameter = ["include_domains", "exclude_domains"].includes(field)
        ? "domains"
        : sdkField;
      setters.push(
        `        public Builder ${sdkField}(${type} ${parameter}) { this.${sdkField} = ${parameter}; return this; }`,
      );
      context[field] = { ...prop, patternJava: prop.pattern ? JSON.stringify(prop.pattern) : "" };
    }
    output.java[`src/main/java/ai/ateve/models/${name}.java`] =
      "// " +
      banner +
      "\n" +
      template(`java/${isRequest ? "request" : "response"}.tpl`, {
        name,
        description: (schema.description ?? name).replaceAll("*/", "* /"),
        imports: [...imports]
          .sort()
          .map((item) => `import ${item};`)
          .join("\n"),
        fields: fields.join("\n"),
        assignments: assignments.join("\n"),
        accessors: accessors.join("\n"),
        builderFields: builderFields.join("\n"),
        setters: setters.join("\n"),
        constants: template(`java/${name}.constants.tpl`, context),
        builderHook:
          template(`java/${name}.builder.tpl`, context) ||
          `        public ${name} build() { return new ${name}(this); }`,
      }) +
      "\n";
  }
  output.js["src/types.ts"] =
    `// ${banner}\n\n${tsModels.join("\n\n")}\n\nexport * from "./options";\n`;
  output.python["src/ateve/models.py"] = `# ${banner}\n${pyModels.join("\n\n\n").trimEnd()}\n`;
  const exports = Object.keys(api.components.schemas)
    .filter((name) => bindings.models?.[name]?.generate !== false)
    .sort();
  output.python["src/ateve/_model_exports.py"] =
    `# ${banner}\nfrom .models import (\n${exports.map((name) => `    ${name},`).join("\n")}\n)\n\n__all__ = [\n${exports.map((name) => `    "${name}",`).join("\n")}\n]\n`;
  return output;
}

export function loadContract(): [Contract, Bindings] {
  return [
    readJson<Contract>(path.join(root, "packages/contract/openapi.json")),
    readJson<Bindings>(path.join(root, "packages/contract/bindings.json")),
  ];
}
